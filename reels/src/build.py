def _render_one(args):
    mod, name, out = args
    try:
        m = load(mod); r = m.REELS[name]()
        t0 = time.time(); p = r.render(out)
        return name, round(r.dur, 1), round(time.time() - t0), os.path.getsize(p) // 1024
    except Exception as e:
        import traceback; return name, "FAILED", repr(e)[:200], traceback.format_exc(limit=2)[-300:]

def render_all(mod, names, out, procs=4):
    from multiprocessing import Pool
    with Pool(procs) as pool:
        for res in pool.imap_unordered(_render_one, [(mod, n, out) for n in names]): print("done", res, flush=True)


def make_index(out_dir="/home/user/sorry-posts/reels"):
    import glob, re
    mods = sorted(os.path.basename(p)[:-3] for p in glob.glob(os.path.join(os.path.dirname(__file__), "scripts", "b*.py")))
    rows = {}
    for mod in mods:
        m = load(mod)
        for name, fn in m.REELS.items():
            r = fn(); rows[r.name] = r
    rows = sorted(rows.items())
    lines = ["# Reels index", "", "Everything in `reels/NNN_*.mp4` is generated by the code in `reels/src` (`python3 build.py <batch> --out ..`). 1080x1920, 30fps, with synthesized music + sound effects (no samples, nothing to license).", "",
             "Captions below are suggested post text. Cultural reels are written as affectionate observational comedy about food, family, hospitality, cars and habits.", ""]
    def vary(cap, idx):
        parts = cap.split(". ")
        if len(parts) >= 2 and parts[-1].lower().startswith("tag "):
            body, cta = ". ".join(parts[:-1]) + ".", parts[-1]
            if idx % 3 == 1: return f"{body} send this to {cta[4:]}"
            if idx % 3 == 2: return f"{body} which one are you?"
        return cap
    for name, r in rows:
        exists = os.path.exists(os.path.join(out_dir, name + ".mp4"))
        idx = int(name[:3]) if name[:3].isdigit() else 0
        lines += [f"## {name} {'' if exists else '(not rendered yet)'}", f"- **length:** {r.dur:.0f}s  |  **music:** {r.style}", f"- **suggested caption:** {vary(r.caption, idx)}", f"- **what happens:** {r.story}", ""]
    open(os.path.join(out_dir, "INDEX.md"), "w").write("\n".join(lines))
    return len(rows)
